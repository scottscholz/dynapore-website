#!/usr/bin/env python3
"""Build the DynaPore site.

  python3 build.py            -> dist/     (production: clean URLs, for Netlify)
  python3 build.py --preview  -> preview/  (relative links, for the claude.ai preview)

Edit page content in src/pages/. Shared header and footer live in src/partials/.
Each page starts with a meta line:  <!--meta {"title": "...", "description": "...", "nav": "applications"} -->

Template tags you can use in pages and partials:
  {{/beta/}}                   link to another page (add #anchor if needed)
  {{@assets/img/x.jpg}}        link to a file in assets/
  {{vid:FILE|POSTER|MOBILE}}   looping muted video in a frame (files in assets/media/, MOBILE optional)
  {{film:FILE|POSTER|MOBILE|portrait}}  like vid, with an optional class (e.g. portrait); all video on the site is silent
  {{ph:LABEL|description}}     visible placeholder box for content still to come
  {{tbc:text}}                 small inline "to be confirmed" marker
  {{svg:name}}                 inline diagram from src/partials/svg/ (generated by tools/gen_svgs.py)
"""
import json, os, re, shutil, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
PREVIEW = '--preview' in sys.argv
OUT = os.path.join(ROOT, 'preview' if PREVIEW else 'dist')
SITE_URL = 'https://www.dynaporetech.com'

def read(p): return open(os.path.join(ROOT, p), encoding='utf-8').read()

LOGO = read('src/partials/logo-inline.html')
HEADER = read('src/partials/header.html')
FOOTER = read('src/partials/footer.html')

HEAD = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<meta name="description" content="{description}">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{description}">
<meta property="og:type" content="website">
<meta property="og:image" content="{site}/assets/media/how-memchip-works-poster.jpg">
<link rel="canonical" href="{site}{route}">
<link rel="icon" href="{{{{@assets/img/favicon.svg}}}}" type="image/svg+xml">
<link rel="preload" href="{{{{@assets/fonts/k2d-latin-300-normal.woff2}}}}" as="font" type="font/woff2" crossorigin>
<link rel="preload" href="{{{{@assets/fonts/k2d-latin-400-normal.woff2}}}}" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="{{{{@assets/css/site.css}}}}">
</head>
<body>
"""

def route_of(rel):
    rel = rel[:-5]  # strip .html
    if rel == 'index': return '/'
    if rel == '404': return '/404.html'
    return '/' + rel + '/'

def out_path(route):
    if route == '/404.html': return '404.html'
    return (route.strip('/') + '/index.html').lstrip('/') if route != '/' else 'index.html'

def rel_prefix(route):
    depth = out_path(route).count('/')
    return '../' * depth

def render(text, route, nav):
    prefix = rel_prefix(route)
    def link(m):
        target = m.group(1)
        path, _, anchor = target.partition('#')
        anchor = ('#' + anchor) if anchor else ''
        if not PREVIEW:
            return path + anchor
        return prefix + out_path(path) + anchor
    def asset(m):
        p = m.group(1)
        return (prefix + p) if PREVIEW else '/' + p
    def vid(m):
        parts = m.group(1).split('|')
        src, poster = parts[0], parts[1]
        mobile = parts[2] if len(parts) > 2 and parts[2] else ''
        a = lambda f: '{{@assets/media/' + f + '}}'
        mob = ' data-src-mobile="%s"' % a(mobile + '.mp4') if mobile else ''
        return ('<div class="media"><video muted loop playsinline preload="none" poster="%s" data-src="%s"%s aria-hidden="true"></video>'
                '<button class="vctl" type="button" aria-label="Play video"></button></div>') % (a(poster + '.jpg'), a(src + '.mp4'), mob)
    def film(m):
        parts = m.group(1).split('|')
        src, poster = parts[0], parts[1]
        mobile = parts[2] if len(parts) > 2 and parts[2] else ''
        cls = ' ' + parts[3] if len(parts) > 3 and parts[3] else ''
        a = lambda f: '{{@assets/media/' + f + '}}'
        mob = ' data-src-mobile="%s"' % a(mobile + '.mp4') if mobile else ''
        return ('<div class="media film%s"><video muted loop playsinline preload="none" poster="%s" data-src="%s"%s aria-hidden="true"></video>'
                '<button class="vctl" type="button" aria-label="Play video"></button></div>') % (cls, a(poster + '.jpg'), a(src + '.mp4'), mob)
    def ph(m):
        label, _, desc = m.group(1).partition('|')
        return '<div class="ph"><span><b>%s</b>%s</span></div>' % (label, desc)
    text = text.replace('{{logo}}', LOGO)
    text = re.sub(r'\{\{svg:([\w-]+)\}\}', lambda m: read('src/partials/svg/' + m.group(1) + '.svg'), text)
    text = re.sub(r'\{\{vid:([^}]+)\}\}', vid, text)
    text = re.sub(r'\{\{film:([^}]+)\}\}', film, text)
    text = re.sub(r'\{\{ph:([^}]+)\}\}', ph, text)
    text = re.sub(r'\{\{tbc:([^}]+)\}\}', r'<span class="tbc">\1</span>', text)
    text = re.sub(r'\{\{active:(\w+)\}\}', lambda m: 'aria-current="page"' if m.group(1) == nav else '', text)
    text = re.sub(r'\{\{@([^}]+)\}\}', asset, text)
    text = re.sub(r'\{\{(/[^}]*)\}\}', link, text)
    return text

def build():
    if os.path.exists(OUT): shutil.rmtree(OUT)
    shutil.copytree(os.path.join(ROOT, 'assets'), os.path.join(OUT, 'assets'))
    pages_dir = os.path.join(ROOT, 'src/pages')
    count = 0
    for dirpath, _, files in os.walk(pages_dir):
        for f in files:
            if not f.endswith('.html'): continue
            rel = os.path.relpath(os.path.join(dirpath, f), pages_dir).replace(os.sep, '/')
            src = open(os.path.join(dirpath, f), encoding='utf-8').read()
            m = re.match(r'\s*<!--meta\s+(\{.*?\})\s*-->', src, re.S)
            meta = json.loads(m.group(1)) if m else {}
            body = src[m.end():] if m else src
            route = route_of(rel)
            head = HEAD.format(title=meta.get('title', 'DynaPore'), description=meta.get('description', ''),
                               site=SITE_URL, route=route)
            html = head + HEADER + '<main id="main">\n' + body + '\n</main>\n' + FOOTER + '</body>\n</html>\n'
            html = render(html, route, meta.get('nav', ''))
            dest = os.path.join(OUT, out_path(route))
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            open(dest, 'w', encoding='utf-8').write(html)
            count += 1
    if not PREVIEW:
        shutil.copy(os.path.join(ROOT, 'src/_redirects'), os.path.join(OUT, '_redirects'))
    leftover = []
    for dirpath, _, files in os.walk(OUT):
        for f in files:
            if f.endswith('.html') and '{{' in open(os.path.join(dirpath, f), encoding='utf-8').read():
                leftover.append(f)
    print('built %d pages into %s%s' % (count, OUT, ('; UNRENDERED TAGS in ' + ', '.join(leftover)) if leftover else ''))

if __name__ == '__main__':
    build()
